def get_disease_info(class_name, confidence):
    info = DISEASE_INFO.get(class_name)
    if info:
        result = dict(info)
        result["confidence"] = round(float(confidence) * 100, 1)
        result["healthy"] = bool(result.get("healthy", False))
        result["class_name"] = class_name
        crop = class_name.split("___")[0].replace("_", " ").replace("(maize)", "").replace("(including sour)", "").strip(" ,")
        result["crop"] = crop
        return result

    parts = class_name.split("___")
    disease_name = parts[1].replace("_", " ").strip() if len(parts) > 1 else class_name
    is_healthy = "healthy" in class_name.lower()
    return {
        "disease": "Healthy" if is_healthy else disease_name,
        "healthy": is_healthy,
        "confidence": round(float(confidence) * 100, 1),
        "severity": "Low" if is_healthy else "Medium",
        "affected_area": "None" if is_healthy else "Unknown",
        "spread": "N/A" if is_healthy else "Unknown",
        "scientific_name": "",
        "class_name": class_name,
        "crop": parts[0].replace("_", " ") if parts else "Unknown",
        "treatment": (
            ""
            if is_healthy
            else "Consult your local agriculture officer or Krishi Vigyan Kendra for treatment advice."
        ),
    }
